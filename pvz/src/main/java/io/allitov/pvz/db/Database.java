package io.allitov.pvz.db;

import java.util.List;

import io.allitov.pvz.model.Order;
import io.allitov.pvz.model.Report;

/**
 * Слой доступа к базе данных пункта выдачи (таблица {@code orders}).
 *
 * <p>Объявляет операции лабораторной работы: приём и выдачу заказов,
 * отмену, поиск, сводный отчёт и массовую обработку закрытых заказов.</p>
 */
public interface Database {

    /**
     * Возвращает список заказов с возможностью поиска по подстроке.
     *
     * <p>Если {@code filter} — пустая строка, возвращаются все заказы.
     * Иначе выполняется поиск без учёта регистра по подстроке в полях
     * {@code order_code}, {@code phone} и {@code parcel_article}.
     * Результат сортируется по времени приёма: свежие заказы сверху.</p>
     *
     * @param filter поисковая подстрока или пустая строка для вывода всех заказов.
     * @return список заказов, отсортированный от свежих к старым; пустой список, если ничего не найдено.
     */
    List<Order> listOrders(String filter);

    /**
     * Принимает заказ в ячейку и возвращает сгенерированный артикул заказа.
     *
     * <p>Контакт получателя задаётся параметром {@code contact}: это телефон
     * <em>или</em> артикул товара — взаимоисключающие варианты, заполнено ровно
     * одно из полей. Ячейка {@code cell} может быть пустой. Код вида
     * {@code PVZ-000042} генерируется и присваивается заказу в рамках одной
     * транзакции с вставкой строки.</p>
     *
     * @param contact телефон получателя или артикул товара (ровно одно из двух).
     * @param cell номер ячейки хранения; может быть пустой строкой.
     * @return сгенерированный код заказа вида {@code PVZ-000042}.
     */
    String addOrder(String contact, String cell);

    /**
     * Выдаёт заказ по его коду.
     *
     * <p>Выдать можно только заказ в статусе {@code ready}: статус переводится
     * в {@code issued} и заполняется поле {@code issued_at}. Если заказ не найден
     * или находится не в статусе {@code ready}, изменения не выполняются.</p>
     *
     * @param code код заказа, например {@code PVZ-000042}.
     * @return {@code true}, если заказ успешно выдан; {@code false}, если заказ не найден или не в статусе {@code ready}.
     */
    boolean issueOrder(String code);

    /**
     * Отменяет заказ по его коду.
     *
     * <p>Отменить можно только заказ в статусе {@code ready}: статус переводится
     * в {@code cancelled}; поле {@code issued_at} при этом не заполняется.
     * Если заказ не найден или находится не в статусе {@code ready}, изменения не выполняются.</p>
     *
     * @param code код заказа, например {@code PVZ-000042}.
     * @return {@code true}, если заказ успешно отменён; {@code false}, если заказ не найден или не в статусе {@code ready}.
     */
    boolean cancelOrder(String code);

    /**
     * Строит сводный отчёт по всем заказам.
     *
     * <p>Подсчитывает количество заказов в каждом из трёх статусов:
     * {@code ready}, {@code issued} и {@code cancelled}.</p>
     *
     * @return отчёт с количеством заказов по каждому статусу.
     */
    Report buildReport();

    /**
     * Возвращает список заказов по статусу.
     *
     * <p>Если {@code status} — пустая строка, возвращаются все заказы
     * (вкладка «Принято» показывает полный список). Иначе выполняется
     * фильтрация по переданному статусу.</p>
     *
     * @param status английский ключ статуса для фильтрации или пустая строка для всех заказов.
     * @return список заказов, удовлетворяющих условию; пустой список, если таких нет.
     */
    List<Order> listByStatus(String status);

    /**
     * Подсчитывает заказы в закрытых статусах.
     *
     * <p>Закрытыми считаются статусы {@code issued} и {@code cancelled}.</p>
     *
     * @return количество заказов в статусах {@code issued} и {@code cancelled}.
     */
    int countClosedOrders();

    /**
     * Удаляет заказы в закрытых статусах.
     *
     * <p>Удаляются все заказы в статусах {@code issued} и {@code cancelled}.</p>
     *
     * @return количество удалённых заказов.
     */
    int deleteClosedOrders();
}
